"""Optional LLM rewrite suggestions via the Gemini REST API (free tier).

Privacy: only profile *content* is sent (headline, about, recent roles, skills) - never the name,
location, contact details or the raw PDF. If there is no API key, or the call fails for any reason
(network, quota, malformed output), the caller falls back to the rule-based rewriter.
"""
from __future__ import annotations

import json
import logging

import httpx

from .. import config
from ..parser.models import Profile
from .models import RewriteSuggestions, SkillReport

log = logging.getLogger(__name__)
URL = "https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent"

PROMPT = """You are an expert LinkedIn profile writer. Improve the profile below.

RULES
- Use ONLY facts present in the profile. Do NOT invent employers, titles, numbers, tools or achievements.
- Headline: 3 distinct options, each <= 150 characters, format like "Role | Skill | Skill | Impact".
- About: first person, 120-250 words, short paragraphs, start sentences with action verbs, include
  the strongest measurable results that already appear in the profile, end with a call to action.
- Return ONLY JSON: {{"headline_options": ["...", "...", "..."], "about": "..."}}

PROFILE
Current headline: {headline}
Current about: {about}
Recent experience:
{experience}
Skills: {skills}
"""


def build_prompt(p: Profile, report: SkillReport) -> str:
    exp = "\n".join(f"- {e.title} at {e.company} ({e.date_range}): {e.description[:500]}"
                    for e in p.experience[:3]) or "(none)"
    skills = ", ".join(dict.fromkeys(report.listed + [h.skill for h in report.mentioned])) or "(none)"
    return PROMPT.format(headline=p.headline or "(none)", about=p.about[:1500] or "(none)",
                         experience=exp, skills=skills)


def gemini_rewrite(p: Profile, report: SkillReport, timeout: float = 25.0) -> RewriteSuggestions | None:
    """Return Gemini suggestions, or None when unavailable (caller then uses the rule-based fallback)."""
    if not config.GEMINI_API_KEY:
        return None
    body = {
        "contents": [{"parts": [{"text": build_prompt(p, report)}]}],
        "generationConfig": {"temperature": 0.4, "responseMimeType": "application/json"},
    }
    try:
        r = httpx.post(URL.format(model=config.GEMINI_MODEL), json=body, timeout=timeout,
                       headers={"x-goog-api-key": config.GEMINI_API_KEY})
        r.raise_for_status()
        text = r.json()["candidates"][0]["content"]["parts"][0]["text"]
        data = json.loads(text)
        options = [str(x)[:220] for x in data["headline_options"]][:3]
        about = str(data["about"]).strip()
        if not options or not about:
            raise ValueError("empty LLM output")
        return RewriteSuggestions(source="gemini", headline_options=options, about=about,
                                  note=f"Generated by {config.GEMINI_MODEL}. Check every claim before publishing.")
    except Exception as exc:                      # network, quota, bad JSON ... -> graceful fallback
        log.warning("Gemini rewrite failed (%s: %s); using rule-based fallback", type(exc).__name__, exc)
        return None
